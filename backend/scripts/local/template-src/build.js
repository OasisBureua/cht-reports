#!/usr/bin/env node
/**
 * Builds templates/executive_summary/<semver>/template.html from
 * template.src.html: embeds the Chillax font files and the CHM logo artwork
 * (from cht-platform-tool's brand components, chm-logo-paths.json) so the
 * PDF prints without network access. Then regenerates
 * src/reports/templates/builtin.ts from that folder's system-prompt.md and
 * template.html (builtin.spec.ts checks they match).
 *
 *   node scripts/local/template-src/build.js <fontsDir> templates/executive_summary/<semver>
 *
 * fontsDir holds chillax-400.woff2, chillax-500.woff2, chillax-600.woff2
 * (Fontshare, ITF Free Font License).
 */

const { readFileSync, writeFileSync } = require('node:fs');
const { basename, join, resolve } = require('node:path');

const [fontsDir, versionDir] = process.argv.slice(2);
if (!fontsDir || !versionDir) {
  console.error('usage: node build.js <fontsDir> templates/executive_summary/<semver>');
  process.exit(2);
}
const out = join(versionDir, 'template.html');

const paths = JSON.parse(readFileSync(join(__dirname, 'chm-logo-paths.json'), 'utf-8'));
const b64 = (s) => Buffer.from(s).toString('base64');

function lockup(mark, letters) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 655 166"><g transform="scale(7.545)" fill="${mark}">${paths.mark
    .map((d) => `<path d="${d}"/>`)
    .join('')}</g><path transform="translate(260 8)" fill="${letters}" d="${paths.letters}"/></svg>`;
}

function mark(color, opacity = 1) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="1.6 1.3 19 18.4"><g fill="${color}" fill-opacity="${opacity}">${paths.mark
    .map((d) => `<path d="${d}"/>`)
    .join('')}</g></svg>`;
}

const values = {
  CHILLAX_400: readFileSync(join(fontsDir, 'chillax-400.woff2')).toString('base64'),
  CHILLAX_500: readFileSync(join(fontsDir, 'chillax-500.woff2')).toString('base64'),
  CHILLAX_600: readFileSync(join(fontsDir, 'chillax-600.woff2')).toString('base64'),
  LOGO_DARK: b64(lockup('#3da4c0', '#485165')),
  LOGO_LIGHT: b64(lockup('#f2f4f8', '#f2f4f8')),
  MARK_KNOWLEDGE: b64(mark('#3da4c0')),
  MARK_SHARING: b64(mark('#ff9e40')),
  MARK_LIGHT: b64(mark('#f2f4f8', 0.1)),
};

const src = readFileSync(join(__dirname, 'template.src.html'), 'utf-8');
const html = src.replace(/__([A-Z0-9_]+)__/g, (m, name) => {
  if (!(name in values)) throw new Error(`unknown token ${m}`);
  return values[name];
});
writeFileSync(out, html);
console.log(`wrote ${out} (${html.length} bytes)`);

const semver = basename(resolve(versionDir));
const prompt = readFileSync(join(versionDir, 'system-prompt.md'), 'utf-8').trim();
const literal = (text) => text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const builtin = `/**
 * Built-in Executive Summary template: used when the packet has no template
 * pointer or its S3 files can't be loaded. Must match
 * \`backend/templates/executive_summary/${semver}/\` (checked in builtin.spec.ts).
 * Generated by scripts/local/template-src/build.js; edit the template source, not this file.
 */

export const BUILTIN_SEMVER = '${semver}';

export const BUILTIN_SYSTEM_PROMPT = \`${literal(prompt)}\`;

export const BUILTIN_HTML_TEMPLATE = \`${literal(html)}\`;
`;
const builtinPath = resolve(__dirname, '../../../src/reports/templates/builtin.ts');
writeFileSync(builtinPath, builtin);
console.log(`wrote ${builtinPath}`);
